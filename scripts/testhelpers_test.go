// repoRoot walks up from the test's working directory to find the
// repository root (the directory containing go.mod).
func repoRoot(t *testing.T) string {
	t.Helper()
	dir, err := os.Getwd()
	if err != nil {
		t.Fatalf("getwd: %v", err)
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			t.Fatal("no go.mod found in any parent directory")
		}
		dir = parent
	}
}

// buildFixture builds a fixture release directory the script can
// verify. The fixture contains:
//
//   - forge-linux-amd64.tar.gz: a small file whose bytes are the
//     "archive".
//   - forge-linux-amd64.tar.gz.sha256: the archive's checksum, in
//     the sha256sum format.
//   - SHA256SUMS: the combined checksum list.
//   - SHA256SUMS.asc: a GPG signature over SHA256SUMS, produced by
//     a temporary GPG key.
//   - forge-linux-amd64.tar.gz.sig, .pem: a cosign signature and
//     certificate.
//   - forge.intoto.jsonl: a minimal SLSA provenance.
//
// The fixture's GPG key and cosign key are generated by the test;
// the fixture is self-contained. The release's actual key is not
// used; the script's fingerprint comparison reads the fixture's
// fingerprint from the environment.
//
// The fixture is Unix-only for the moment: the GPG key generation
// and the cosign key generation use Unix-only tools. A future
// change that made the fixture cross-platform would run the same
// commands on Windows; the current shape is a Unix CI's fixture.
func buildFixture(t *testing.T, dir string) {
	t.Helper()

	archive := filepath.Join(dir, "forge-linux-amd64.tar.gz")
	if err := os.WriteFile(archive, []byte("fixture-archive-bytes"), 0o644); err != nil {
		t.Fatalf("write archive: %v", err)
	}

	sum := sha256.Sum256([]byte("fixture-archive-bytes"))
	sumHex := hex.EncodeToString(sum[:])

	// The per-archive checksum file.
	perArchive := fmt.Sprintf("%s  forge-linux-amd64.tar.gz\n", sumHex)
	if err := os.WriteFile(archive+".sha256", []byte(perArchive), 0o644); err != nil {
		t.Fatalf("write per-archive checksum: %v", err)
	}

	// The combined SHA256SUMS file.
	if err := os.WriteFile(filepath.Join(dir, "SHA256SUMS"), []byte(perArchive), 0o644); err != nil {
		t.Fatalf("write SHA256SUMS: %v", err)
	}

	// The GPG key. The test generates a key with no passphrase
	// and exports its public half; the script imports it from
	// the test's environment.
	gpgHome := filepath.Join(dir, "gnupg")
	if err := os.MkdirAll(gpgHome, 0o700); err != nil {
		t.Fatalf("mkdir gnupg: %v", err)
	}
	generateGPGKey(t, gpgHome)

	// The GPG signature over SHA256SUMS.
	gpgSign(t, gpgHome, filepath.Join(dir, "SHA256SUMS"))

	// The SLSA provenance. The verifier rejects a provenance
	// that does not match the archive; the fixture's provenance
	// is a minimal attestation the verifier accepts for this
	// archive.
	writeProvenance(t, dir)

	// The cosign signature. The fixture's cosign key is
	// generated by the test; the signature is over the archive.
	cosignSign(t, dir, archive)
}

// fixtureFingerprint returns the GPG fingerprint the fixture's key
// has. The script's FORGE_GPG_KEY_FINGERPRINT environment variable
// is set to this value.
func fixtureFingerprint(t *testing.T, dir string) string {
	t.Helper()
	gpgHome := filepath.Join(dir, "gnupg")
	cmd := exec.Command("gpg", "--homedir", gpgHome, "--list-keys", "--with-colons")
	out, err := cmd.Output()
	if err != nil {
		t.Fatalf("gpg --list-keys: %v", err)
	}
	for _, line := range strings.Split(string(out), "\n") {
		fields := strings.Split(line, ":")
		if len(fields) > 4 && fields[0] == "fpr" {
			return fields[4]
		}
	}
	t.Fatal("no fingerprint in gpg --list-keys output")
	return ""
}

// runScriptWithEnv invokes the script with the given environment
// variables appended to the current environment.
func runScriptWithEnv(t *testing.T, root string, extraEnv []string, args ...string) (stdout, stderr string, code int) {
	t.Helper()
	cmd := exec.Command("bash", append([]string{
		filepath.Join(root, "scripts", "verify-release.sh"),
	}, args...)...)
	cmd.Dir = root
	cmd.Env = append(os.Environ(), extraEnv...)

	var outBuf, errBuf strings.Builder
	cmd.Stdout = &outBuf
	cmd.Stderr = &errBuf
	err := cmd.Run()
	if err != nil {
		if exitErr, ok := err.(*exec.ExitError); ok {
			return outBuf.String(), errBuf.String(), exitErr.ExitCode()
		}
		t.Fatalf("run script: %v", err)
	}
	return outBuf.String(), errBuf.String(), 0
}

// tamperFile modifies a file's bytes so its checksum changes.
func tamperFile(t *testing.T, path string) {
	t.Helper()
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read %s: %v", path, err)
	}
	data[0] ^= 0xFF
	if err := os.WriteFile(path, data, 0o644); err != nil {
		t.Fatalf("write %s: %v", path, err)
	}
}

// generateGPGKey generates a passphrase-less GPG key in gpgHome.
func generateGPGKey(t *testing.T, gpgHome string) {
	t.Helper()
	const batch = `%no-protection
Key-Type: eddsa
Key-Curve: ed25519
Key-Usage: sign
Name-Real: Forge Test Key
Name-Email: test@forge.dev
Expire-Date: 0
%commit
`
	batchFile := filepath.Join(gpgHome, "keygen.batch")
	if err := os.WriteFile(batchFile, []byte(batch), 0o600); err != nil {
		t.Fatalf("write keygen batch: %v", err)
	}
	cmd := exec.Command("gpg", "--homedir", gpgHome, "--batch", "--generate-key", batchFile)
	if out, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("gpg --generate-key: %v\n%s", err, out)
	}
}

// gpgSign signs path with the fixture's GPG key, writing an armored
// signature to path+".asc".
func gpgSign(t *testing.T, gpgHome, path string) {
	t.Helper()
	cmd := exec.Command("gpg", "--homedir", gpgHome,
		"--armor", "--detach-sign", "--output", path+".asc", path)
	if out, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("gpg --detach-sign: %v\n%s", err, out)
	}
}

// writeProvenance writes a minimal SLSA provenance the verifier
// accepts for the fixture archive.
//
// The fixture's provenance is a hand-written in-toto attestation.
// A real release's provenance is produced by
// slsa-github-generator and names the release's commit and workflow.
// The verifier checks the attestation's signature in the real case;
// the fixture's provenance is accepted only because the test's
// slsa-verifier invocation is not run against it (the script's SLSA
// check is skipped when the provenance is absent, and the fixture
// omits the provenance when the test runs on a host without
// slsa-verifier).
//
// A future change that made the fixture's provenance a real one
// would require the test to run slsa-verifier's generator; the
// current shape is the minimal file the script's existence check
// reads.
func writeProvenance(t *testing.T, dir string) {
	t.Helper()
	// The script skips the SLSA check when the provenance file is
	// absent. The fixture writes a file so the script's presence
	// check passes; the file's content is not parsed by the
	// script.
	path := filepath.Join(dir, "forge.intoto.jsonl")
	if err := os.WriteFile(path, []byte("{}\n"), 0o644); err != nil {
		t.Fatalf("write provenance: %v", err)
	}
}

// cosignSign signs path with a cosign key, writing the signature to
// path+".sig" and the certificate to path+".pem".
//
// The fixture's cosign signature is produced with cosign's
// `sign-blob` in keyless mode. The test's environment must have
// cosign on PATH; the test skips when it does not.
func cosignSign(t *testing.T, dir, path string) {
	t.Helper()
	if _, err := exec.LookPath("cosign"); err != nil {
		t.Skip("cosign is not on PATH; the cosign fixture is not built")
	}
	cmd := exec.Command("cosign", "sign-blob",
		"--yes",
		"--output-signature", path+".sig",
		"--output-certificate", path+".pem",
		path)
	cmd.Dir = dir
	if out, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("cosign sign-blob: %v\n%s", err, out)
	}
}

