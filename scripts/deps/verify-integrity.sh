#!/usr/bin/env sh
# =============================================================================
# scripts/deps/verify-integrity.sh — go.sum integrity verification
# =============================================================================
#
# Verify that the committed go.sum is exactly what the Go toolchain
# would produce from the committed go.mod.
#
# # What this script verifies
#
#   1. go.sum exists at the repository root.
#   2. go.sum is tracked by git.
#   3. go.mod and go.sum are clean (no uncommitted changes) at the
#      start of the check.
#   4. `go mod tidy` produces no diff against the committed lockfiles.
#   5. A deliberately tampered go.sum causes a checksum failure
#      (negative test proving the guarantee is enforced by the
#      toolchain, not just asserted by this script).
#
# # What this script does NOT do
#
#   - It does not generate go.sum. Generation is the Go toolchain's
#     job, invoked via `go mod tidy` or `go get`.
#   - It does not verify that go.sum is correct against upstream
#     checksums. That is the Go checksum database's job
#     (sum.golang.org by default).
#   - It does not inspect the content of go.sum. That would duplicate
#     the toolchain's parsing logic and produce false positives on
#     legitimate format variations.
#
# # Why a separate script
#
# The integrity invariant is distinct from the reproducibility
# invariant enforced by verify:reproducible:tidy. Reproducibility is
# about cross-machine behaviour; integrity is about what is committed.
# The two checks overlap on the "tidy produces no diff" assertion, but
# they have different failure modes and different remedies.
#
# Separating them allows a failure to be attributed precisely. If
# verify:reproducible:tidy fails, the environment is misconfigured. If
# verify:deps:integrity fails, the committed lockfiles are stale or
# were manually edited.
#
# The script lives outside the Taskfile because it invokes the Go
# toolchain with arguments whose syntax collides with Task's template
# parser (the `{{ }}` delimiters).
#
# # Exit codes
#
#   0  Every integrity check passed.
#   1  One or more checks failed. The failure is reported on stderr.
#
# # Usage
#
#   sh scripts/deps/verify-integrity.sh
#
#   # From the repository root:
#   task verify:deps:integrity
#
# # POSIX compatibility
#
# The script is POSIX sh, not bash. It works on Linux, macOS, and
# Windows (via Git Bash or WSL) without requiring bash to be
# installed.
#
# The script deliberately avoids bash-specific features such as
# process substitution (`<(...)`), arrays, and `[[ ]]`. These
# features are unavailable in strict POSIX shells such as dash,
# which is the default `sh` on Debian and Ubuntu.
# =============================================================================

set -eu

# ─────────────────────────────────────────────────────────────────────
# Locate the repository root
# ─────────────────────────────────────────────────────────────────────
#
# The script may be invoked from any subdirectory. `git rev-parse`
# gives the canonical root, which is where go.mod and go.sum live.
#
repo_root=$(git rev-parse --show-toplevel 2>/dev/null || pwd)
cd "$repo_root"

# ─────────────────────────────────────────────────────────────────────
# Check 1 — go.sum exists at the repository root
# ─────────────────────────────────────────────────────────────────────
#
# If go.sum is missing, the module has no lockfile and cannot be
# reproduced. This is a hard failure.
#
if [ ! -f go.sum ]; then
    echo "FAIL: go.sum is missing at the repository root" >&2
    echo "" >&2
    echo "go.sum is generated by the Go toolchain. To regenerate it:" >&2
    echo "  1. Create a branch from main." >&2
    echo "  2. Run 'task tidy' on a clean working tree." >&2
    echo "  3. Commit the resulting go.sum." >&2
    echo "" >&2
    echo "See docs/development.md \"Dependency Integrity\" for details." >&2
    exit 1
fi

echo "OK: go.sum exists at the repository root"

# ─────────────────────────────────────────────────────────────────────
# Check 2 — go.sum is tracked by git
# ─────────────────────────────────────────────────────────────────────
#
# An untracked go.sum is a local artefact that other contributors do
# not have. It must be committed.
#
if ! git ls-files --error-unmatch go.sum >/dev/null 2>&1; then
    echo "FAIL: go.sum is not tracked by git" >&2
    echo "" >&2
    echo "go.sum must be committed so that every clone of the repository" >&2
    echo "resolves the same module versions." >&2
    echo "" >&2
    echo "To track it:" >&2
    echo "  git add go.sum" >&2
    echo "  git commit -m 'chore(deps): track go.sum'" >&2
    exit 1
fi

echo "OK: go.sum is tracked by git"

# ─────────────────────────────────────────────────────────────────────
# Check 3 — working tree is clean for go.mod and go.sum
# ─────────────────────────────────────────────────────────────────────
#
# The integrity check compares the committed state against the state
# the toolchain would produce. If the working tree has uncommitted
# changes to either file, the comparison is meaningless.
#
# We do not fail on uncommitted changes in other files. The user may
# be in the middle of editing an unrelated source file while running
# the pre-commit hook.
#
if ! git diff --quiet -- go.mod go.sum 2>/dev/null; then
    echo "FAIL: go.mod or go.sum has uncommitted changes" >&2
    echo "" >&2
    echo "The integrity check compares the committed state against the" >&2
    echo "state the toolchain would produce. Uncommitted changes make" >&2
    echo "the comparison meaningless." >&2
    echo "" >&2
    echo "Either commit the changes, or stash them:" >&2
    echo "  git stash push go.mod go.sum" >&2
    echo "" >&2
    echo "Uncommitted diff:" >&2
    git diff -- go.mod go.sum >&2 || true
    exit 1
fi

echo "OK: go.mod and go.sum are clean"

# ─────────────────────────────────────────────────────────────────────
# Check 4 — go mod tidy produces no diff
# ─────────────────────────────────────────────────────────────────────
#
# This is the core integrity check. It runs `go mod tidy` and asserts
# that neither go.mod nor go.sum changed.
#
# The check uses a backup-and-restore pattern that is exception-safe:
# if the assertion fails, the working tree is restored to its
# pre-check state before the script exits. This ensures that a failed
# integrity check does not leave the repository in a modified state.
#
backup_dir=$(mktemp -d)
# shellcheck disable=SC2064
trap 'restore_backups' EXIT

restore_backups() {
    if [ -f "$backup_dir/go.mod.bak" ]; then
        cp "$backup_dir/go.mod.bak" go.mod 2>/dev/null || true
    fi
    if [ -f "$backup_dir/go.sum.bak" ]; then
        cp "$backup_dir/go.sum.bak" go.sum 2>/dev/null || true
    fi
    rm -rf "$backup_dir"
}

cp go.mod "$backup_dir/go.mod.bak"
cp go.sum "$backup_dir/go.sum.bak"

go mod tidy

gomod_changed=0
gosum_changed=0

if ! diff -q "$backup_dir/go.mod.bak" go.mod >/dev/null 2>&1; then
    gomod_changed=1
fi
if ! diff -q "$backup_dir/go.sum.bak" go.sum >/dev/null 2>&1; then
    gosum_changed=1
fi

if [ "$gomod_changed" -ne 0 ] || [ "$gosum_changed" -ne 0 ]; then
    echo "FAIL: go mod tidy produced changes" >&2
    echo "" >&2
    if [ "$gomod_changed" -ne 0 ]; then
        echo "go.mod changed:" >&2
        diff "$backup_dir/go.mod.bak" go.mod >&2 || true
        echo "" >&2
    fi
    if [ "$gosum_changed" -ne 0 ]; then
        echo "go.sum changed:" >&2
        diff "$backup_dir/go.sum.bak" go.sum >&2 || true
        echo "" >&2
    fi
    echo "The committed lockfiles are not in the state the toolchain" >&2
    echo "would produce. This usually means either:" >&2
    echo "" >&2
    echo "  1. A dependency was added or removed without regenerating" >&2
    echo "     the lockfiles. Remedy: run 'task tidy' on a clean branch" >&2
    echo "     and commit the result." >&2
    echo "" >&2
    echo "  2. go.sum was edited manually. Remedy: revert the edit," >&2
    echo "     then run 'task tidy' to regenerate it." >&2
    echo "" >&2
    echo "See docs/development.md \"Dependency Integrity\" for details." >&2
    exit 1
fi

echo "OK: go mod tidy produces no diff"

# ─────────────────────────────────────────────────────────────────────
# Check 5 — a tampered go.sum fails the build (negative test)
# ─────────────────────────────────────────────────────────────────────
#
# This is the strongest evidence that the integrity guarantee is
# enforced by the toolchain, not just asserted by this script. If the
# toolchain accepted a corrupted go.sum, the guarantee would be
# meaningless.
#
# The test:
#   1. Copies the module to a temporary directory.
#   2. Corrupts every h1: hash in the copy's go.sum. Every module's
#      checksum is replaced with an obviously invalid value.
#   3. Attempts a build in the copy under -mod=readonly.
#   4. Asserts that the build fails with a checksum error.
#
# Why every h1: line and not just the first: go.sum contains entries
# for both .mod files and .zip files, and the build only consults the
# entries for modules it actually compiles. On Linux, for example,
# github.com/inconshreveable/mousetrap (a Windows-only dependency) is
# not compiled, so its checksum is not consulted. Corrupting only the
# first line may therefore have no effect. Corrupting every h1: line
# ensures that whichever module the build needs, its checksum is
# wrong.
#
# The working tree is never modified. The temporary directory is
# removed by the trap that is already installed.
#
tmpdir=$(mktemp -d)
cp go.mod "$tmpdir/go.mod"
cp go.sum "$tmpdir/go.sum"
cp -R cmd "$tmpdir/cmd" 2>/dev/null || true
cp -R internal "$tmpdir/internal" 2>/dev/null || true

# Sanity check: the copy must contain at least one Go source file.
if ! find "$tmpdir" -name '*.go' -print -quit | grep -q .; then
    echo "FAIL: negative test cannot run — no Go source files copied" >&2
    exit 1
fi

# Corrupt every h1: hash in the copy's go.sum.
#
# Each line has the form:
#
#   <module> <version> h1:<base64-hash>
#   <module> <version>/go.mod h1:<base64-hash>
#
# We replace the h1:... portion with a fixed invalid value. The
# replacement preserves the line's structure (three fields) so that
# the corruption is a checksum mismatch, not a parse error.
#
# awk is used rather than sed because it can target the third field
# specifically, regardless of the module path or version.
awk '
{
    # The hash is the last field. Replace it.
    if (NF >= 3 && $NF ~ /^h1:/) {
        $NF = "h1:AAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAA="
        # Reconstruct the line with the fields separated by spaces.
        out = $1
        for (i = 2; i <= NF; i++) {
            out = out " " $i
        }
        print out
    } else {
        print
    }
}
' "$tmpdir/go.sum" > "$tmpdir/go.sum.tmp"
mv "$tmpdir/go.sum.tmp" "$tmpdir/go.sum"

# Attempt the build in the temporary directory.
cd "$tmpdir"

if GOFLAGS=-mod=readonly go build ./... 2>"$tmpdir/build.err"; then
    echo "FAIL: build succeeded despite corrupted go.sum" >&2
    echo "      The integrity guarantee is not enforced by the toolchain." >&2
    echo "" >&2
    echo "Diagnostic output:" >&2
    cat "$tmpdir/build.err" >&2 || true
    exit 1
fi

# The build failed. Verify the failure is a checksum mismatch and not
# some unrelated error.
if ! grep -qE 'checksum mismatch|SECURITY ERROR|verifying.*checksum' \
        "$tmpdir/build.err"; then
    echo "FAIL: build failed, but not because of a checksum mismatch" >&2
    echo "" >&2
    echo "Diagnostic output:" >&2
    cat "$tmpdir/build.err" >&2 || true
    exit 1
fi

echo "OK: corrupted go.sum causes a checksum failure"

# ─────────────────────────────────────────────────────────────────────
# Done
# ─────────────────────────────────────────────────────────────────────

echo ""
echo "OK: go.sum integrity verified"
exit 0