package main

import (
	"fmt"
	"os"
	"regexp"

	"github.com/thapelomagqazana/forge/internal/version"
)

// channelOf wraps internal/version.ChannelOf. The wrapper exists so
// this tool depends on the same pure function the release pipeline
// uses; there is no second implementation to drift.
func channelOf(tag string) (string, error) {
	c, err := version.ChannelOf(tag)
	if err != nil {
		return "", err
	}
	return c.String(), nil
}

// cmdChannel prints the channel of a single tag. It exits non-zero if
// the tag matches no channel. CI uses it to route a tag to a release
// channel; the error message names the tag so a rejected release is
// legible.
func cmdChannel(args []string, stdout, stderr *os.File) int {
	if len(args) != 1 {
		fmt.Fprintln(stderr, "usage: forge-internal-version channel <tag>")
		return 2
	}
	tag := args[0]
	ch, err := channelOf(tag)
	if err != nil {
		fmt.Fprintf(stderr, "forge-internal-version: %v\n", err)
		return 1
	}
	fmt.Fprintln(stdout, ch)
	return 0
}

// cmdTagTable prints a deterministic table of example tags and the
// channel each routes to. The table is the executable form of
// docs/reference/release-channels.md's tag-pattern table; it is
// regenerated by `task version:tag-table` when the doc changes.
//
// The examples are fixed here, not read from the YAML, so a change to
// the YAML that contradicts the doc is visible as a diff in this
// table's output.
func cmdTagTable(stdout, stderr *os.File) int {
	type row struct {
		tag     string
		channel string
		err     string
	}
	rows := []row{
		// stable
		{"v0.1.0", "", ""},
		{"v1.0.0", "", ""},
		{"v1.4.2", "", ""},
		{"v10.20.30", "", ""},
		// prerelease
		{"v1.0.0-alpha.1", "", ""},
		{"v1.0.0-beta.3", "", ""},
		{"v1.0.0-rc.2", "", ""},
		// nightly
		{"v1.5.0-nightly.20260601", "", ""},
		// rejected
		{"1.0.0", "", ""},
		{"v1.0", "", ""},
		{"v1.0.0-", "", ""},
		{"v1.0.0-gamma.1", "", ""},
		{"v1.0.0-nightly.2026060", "", ""},
		{"v1.0.0+build", "", ""},
	}
	for i := range rows {
		ch, err := channelOf(rows[i].tag)
		if err != nil {
			rows[i].err = "rejected"
			continue
		}
		rows[i].channel = ch
	}

	const fmtLine = "%-26s %-12s %s\n"
	fmt.Fprintf(stdout, fmtLine, "TAG", "CHANNEL", "NOTES")
	fmt.Fprintf(stdout, fmtLine, "---", "-------", "-----")
	for _, r := range rows {
		notes := r.err
		if notes == "" {
			notes = ""
		}
		fmt.Fprintf(stdout, fmtLine, r.tag, r.channel, notes)
	}
	return 0
}

// tagPatternTable is the set of regexes the docs claim. It is asserted
// against internal/version.ChannelOf by TestTagPatternTable in this
// package. Keeping the table here, in the tool, means a change to the
// doc that adds a pattern must add it in one place: internal/version.
var tagPatternTable = map[string]*regexp.Regexp{
	"stable":     regexp.MustCompile(`^v\d+\.\d+\.\d+$`),
	"prerelease": regexp.MustCompile(`^v\d+\.\d+\.\d+-(alpha|beta|rc)\.\d+$`),
	"nightly":    regexp.MustCompile(`^v\d+\.\d+\.\d+-nightly\.\d{8}$`),
}
