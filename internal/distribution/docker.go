package distribution

import (
	"bytes"
	"fmt"
	"strings"
	"text/template"
)

// dockerAdapter renders the Dockerfile and the image's build args.
//
// # The image's shape
//
// The image is a minimal OCI image: a scratch base with the Forge
// binary at /usr/local/bin/forge and a non-root user. The image is
// multi-arch (linux/amd64 and linux/arm64); the pipeline builds one
// image per architecture and pushes a manifest list.
//
// # Why scratch, not alpine
//
// Forge is a static binary (CGO_ENABLED=0, per the build's
// configuration). A scratch image holds only the binary and the
// CA certificates. An alpine base would add a shell and a package
// manager the binary does not need, and would enlarge the image's
// attack surface. A user who needs a shell uses the binary directly
// or the archive.
//
// # Why the adapter returns a Dockerfile, not the image
//
// The adapter is pure: it renders files. Building and pushing an
// image is an I/O operation the caller performs. The caller runs
// `docker buildx build --platform linux/amd64,linux/arm64 -t
// ghcr.io/forge-cli/forge:<version> --push .`; the adapter's
// Dockerfile is the input.
type dockerAdapter struct{}

// Channel returns ChannelDocker.
func (dockerAdapter) Channel() Channel { return ChannelDocker }

// Manifests returns the Dockerfile.
//
// The Dockerfile copies the pre-built binary from the build context.
// The pipeline stages the binary in the context before invoking
// `docker build`; the Dockerfile's COPY line reads it.
//
// The function returns ErrNotApplicable never: every release channel
// publishes to the container registry. A nightly's image is tagged
// <version>-nightly; the caller chooses the tag.
func (dockerAdapter) Manifests(r Release) ([]Manifest, error) {
	required := []string{"linux/amd64", "linux/arm64"}
	if _, err := platformURLs(r, required); err != nil {
		return nil, err
	}

	var buf bytes.Buffer
	if err := dockerTmpl.Execute(&buf, dockerData{
		Version: strings.TrimPrefix(r.Version, "v"),
	}); err != nil {
		return nil, fmt.Errorf("docker: render Dockerfile: %w", err)
	}
	return []Manifest{{
		Path:    "Dockerfile",
		Content: buf.Bytes(),
		Mode:    0o644,
	}}, nil
}

// dockerData is the template's input.
type dockerData struct {
	// Version is the release's version without its leading "v",
	// e.g. "1.4.2". It is the value of the image's
	// org.opencontainers.image.version label.
	Version string
}

// dockerTmpl is the Dockerfile's template.
//
// The template is frozen by internal/distribution/testdata/docker.golden.Dockerfile.
// The image is a scratch base with the binary and the CA bundle. The
// non-root user is uid 65532 (the distroless convention); a scratch
// image has no /etc/passwd, so the user is created by the COPY's
// --chown and the USER directive's numeric uid.
//
// The template is a Go text/template. Its only action is
// `{{ .Version }}` in the LABEL stanza. The Dockerfile's other braces
// are not template actions; the template's delimiters are `{{` and
// `}}`, and the Dockerfile's body has no other `{{`.
var dockerTmpl = template.Must(template.New("docker").Parse(dockerfile))

// dockerfile is the Dockerfile's template body.
//
// The constant is a backtick-delimited raw string. A raw string
// cannot contain a backtick; the Dockerfile's body must not contain
// one. A future Dockerfile line that needs a backtick (a shell
// command substitution, for example) would require changing this
// constant to a double-quoted string and escaping every backslash —
// a change that is easy to get wrong. The current Dockerfile has no
// backtick, so the raw string is the right choice.
const dockerfile = `# This file is generated by Forge's release pipeline (WBS 17.5.4).
# Do not edit it by hand. The pipeline overwrites it on every release.
#
# The image is a scratch base with the Forge binary. The binary is a
# static build (CGO_ENABLED=0); a scratch base is sufficient. The
# binary is staged by the pipeline before the build; the COPY line
# reads ./forge from the build context.

FROM scratch

# The CA bundle is copied from the build stage's base. A scratch
# image has none; a user who runs forge against an HTTPS endpoint
# needs one.
COPY --from=alpine:3.20 /etc/ssl/certs/ca-certificates.crt /etc/ssl/certs/ca-certificates.crt

# The binary. The pipeline stages it at ./forge in the build context.
COPY --chown=65532:65532 ./forge /usr/local/bin/forge

# A non-root user. The uid is the distroless convention; a scratch
# image has no /etc/passwd, so the numeric uid is what matters.
USER 65532:65532

ENTRYPOINT ["/usr/local/bin/forge"]
CMD ["--help"]

# Labels. The version label is the release's; the source label is the
# repository. A user who runs docker inspect sees the version.
LABEL org.opencontainers.image.title="Forge" \
      org.opencontainers.image.description="Forge is a foundation manager for software projects." \
      org.opencontainers.image.version="{{ .Version }}" \
      org.opencontainers.image.source="https://github.com/forge-cli/forge" \
      org.opencontainers.image.licenses="MPL-2.0"
`
