package distribution

import (
	"bytes"
	"fmt"
	"strings"
	"text/template"
)

// homebrewAdapter renders the Homebrew formula for the release.
//
// # The formula's shape
//
// A Homebrew formula is a Ruby file with a class name, a version, a
// license, platform-specific URLs, and platform-specific SHA-256s.
// The formula this adapter renders is a "bottle-less" formula: it
// downloads the release archive and extracts it, rather than
// downloading a pre-built bottle.
//
// A bottle is faster to install — Homebrew downloads a tarball and
// does not run the install script — but a bottle must be built on
// Homebrew's infrastructure, which requires a pull request to
// Homebrew/homebrew-core. Forge is not in homebrew-core; it is in a
// tap. A tap's formula is installed from source, which for a Go binary
// means downloading the release archive. The formula's `install`
// method extracts the binary.
//
// # Why a tap, not homebrew-core
//
// homebrew-core requires every formula to meet a set of criteria
// (notability, license, build from source). Forge is an early-stage
// project; a tap is the right place. A future migration to
// homebrew-core is a separate change and does not affect this
// adapter's output: the formula's content is the same; only its
// repository moves.
//
// # The template
//
// The template is in this file, not in a separate file, because a
// separate file would be a second place to edit and a second place to
// forget. The template's variables are the release's fields; a change
// to the formula's shape is a change to the template.
type homebrewAdapter struct{}

// Channel returns ChannelHomebrew.
func (homebrewAdapter) Channel() Channel { return ChannelHomebrew }

// Manifests returns the formula.
//
// The formula is one file: Formula/forge.rb. The path is relative to
// the tap's repository root.
//
// The function returns ErrNotApplicable when the release's channel is
// "nightly": a nightly is a snapshot, not a release, and a tap's
// formula should not name a snapshot.
func (homebrewAdapter) Manifests(r Release) ([]Manifest, error) {
	if r.Channel == "nightly" {
		return nil, fmt.Errorf("%w: homebrew does not publish nightly releases", ErrNotApplicable)
	}
	// The formula needs both macOS and both Linux archives. A
	// release that is missing one is a release Homebrew cannot
	// install on that platform; the adapter records the platform
	// in the error.
	required := []string{"darwin/amd64", "darwin/arm64", "linux/amd64", "linux/arm64"}
	urls, err := platformURLs(r, required)
	if err != nil {
		return nil, err
	}

	data := homebrewData{
		Version:        strings.TrimPrefix(r.Version, "v"),
		License:        "MPL-2.0",
		Homepage:       "https://forge.dev",
		Description:    "Forge is a foundation manager for software projects.",
		DarwinAMD64URL: urls["darwin/amd64"].URL,
		DarwinAMD64SHA: urls["darwin/amd64"].SHA256,
		DarwinARM64URL: urls["darwin/arm64"].URL,
		DarwinARM64SHA: urls["darwin/arm64"].SHA256,
		LinuxAMD64URL:  urls["linux/amd64"].URL,
		LinuxAMD64SHA:  urls["linux/amd64"].SHA256,
		LinuxARM64URL:  urls["linux/arm64"].URL,
		LinuxARM64SHA:  urls["linux/arm64"].SHA256,
	}

	var buf bytes.Buffer
	if err := homebrewTmpl.Execute(&buf, data); err != nil {
		return nil, fmt.Errorf("homebrew: render formula: %w", err)
	}
	return []Manifest{{
		Path:    "Formula/forge.rb",
		Content: buf.Bytes(),
		Mode:    0o644,
	}}, nil
}

// homebrewData is the template's input.
type homebrewData struct {
	Version        string
	License        string
	Homepage       string
	Description    string
	DarwinAMD64URL string
	DarwinAMD64SHA string
	DarwinARM64URL string
	DarwinARM64SHA string
	LinuxAMD64URL  string
	LinuxAMD64SHA  string
	LinuxARM64URL  string
	LinuxARM64SHA  string
}

// homebrewTmpl is the formula template.
//
// The template is frozen by internal/distribution/testdata/homebrew.golden.rb.
// A change to it changes the golden; the change is reviewed as a
// formula change.
//
// The template deliberately does not use `on_macos`/`on_linux` and
// `Hardware::CPU.arm?` in the `url` stanza. Homebrew's `url` stanza is
// evaluated at install time and must select exactly one URL; the
// `on_macos`/`on_linux` blocks are the way to express that. A formula
// that put both URLs in one `url` stanza would not install.
var homebrewTmpl = template.Must(template.New("homebrew").Parse(homebrewFormula))

const homebrewFormula = `# typed: false
# frozen_string_literal: true

# This file is generated by Forge's release pipeline (WBS 17.5.4).
# Do not edit it by hand. The pipeline overwrites it on every release.
#
# The formula's upstream is https://github.com/forge-cli/forge. A
# change to the formula's shape is a change to
# internal/distribution/homebrew.go's homebrewFormula constant.

class Forge < Formula
  desc "{{ .Description }}"
  homepage "{{ .Homepage }}"
  version "{{ .Version }}"
  license "{{ .License }}"

  on_macos do
    if Hardware::CPU.arm?
      url "{{ .DarwinARM64URL }}"
      sha256 "{{ .DarwinARM64SHA }}"
    else
      url "{{ .DarwinAMD64URL }}"
      sha256 "{{ .DarwinAMD64SHA }}"
    end
  end

  on_linux do
    if Hardware::CPU.arm?
      url "{{ .LinuxARM64URL }}"
      sha256 "{{ .LinuxARM64SHA }}"
    else
      url "{{ .LinuxAMD64URL }}"
      sha256 "{{ .LinuxAMD64SHA }}"
    end
  end

  def install
    bin.install "forge"
  end

  test do
    system "#{bin}/forge", "version", "--format=json"
  end
end
`

// platformURL is the URL and checksum for a platform's archive.
type platformURL struct {
	URL    string
	SHA256 string
}

// platformURLs returns the URL and checksum for each required
// platform. It returns ErrUnsupportedPlatform if a required platform
// is missing from the release.
func platformURLs(r Release, required []string) (map[string]platformURL, error) {
	out := make(map[string]platformURL, len(required))
	for _, name := range required {
		a, ok := r.Archives[name]
		if !ok {
			return nil, fmt.Errorf("%w: homebrew requires %s", ErrUnsupportedPlatform, name)
		}
		out[name] = platformURL{
			URL:    fmt.Sprintf("https://github.com/forge-cli/forge/releases/download/%s/%s", r.Version, a.Name),
			SHA256: a.SHA256,
		}
	}
	return out, nil
}
